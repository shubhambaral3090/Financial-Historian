"""Legacy SEC layouts must retain negative figures and row context."""
from financial_historian.extract import parse_filing_html
from financial_historian.models import Filing


FILING = Filing("0000320193-16-000001", "10-K", "2016-10-26", "2016-09-24", "report.htm", "https://www.sec.gov/Archives/edgar/data/320193/report.htm")


def legacy_table(title, rows):
    return f"""<h2>{title}</h2><p>Years ended (in millions, except per share amounts), USD</p>
    <table><tr><td></td><td colspan="3">September 24, 2016</td><td></td>
    <td colspan="3">September 26, 2015</td><td></td><td colspan="3">September 27, 2014</td></tr>
    {rows}</table>""".encode()


def legacy_row(label, values):
    cells = []
    for value in values:
        # SEC HTML frequently splits the closing parenthesis into its own cell.
        cells.append(f'<td>$</td><td>{"(" if value < 0 else ""}{abs(value):,}</td><td>{")" if value < 0 else ""}</td>')
    return f'<tr><td>{label}</td>{"<td></td>".join(cells)}</tr>'


def test_legacy_cashflow_grouped_date_columns_keep_negative_totals_and_outflows():
    rows = legacy_row("Cash generated by operating activities", [66_231, 81_266, 59_713])
    rows += '<tr><td>Investing activities:</td></tr>'
    rows += legacy_row("Payments for acquisition of property, plant and equipment", [-12_734, -11_247, -9_571])
    rows += legacy_row("Cash used in investing activities", [-45_977, -56_274, -22_579])
    rows += '<tr><td>Financing activities:</td></tr>'
    rows += legacy_row("Cash used in financing activities", [-20_483, -17_716, -37_549])
    facts = parse_filing_html(legacy_table("Consolidated Statements of Cash Flows", rows), FILING)
    assert len(facts) == 12
    latest = {fact.label: fact for fact in facts if fact.end == "2016-09-24"}
    assert latest["Payments for acquisition of property, plant and equipment"].value == -12_734_000_000
    assert latest["Cash used in investing activities"].presentation_value == -45_977_000_000
    assert latest["Cash used in financing activities"].value == -20_483_000_000
    assert latest["Cash used in financing activities"].section == "Financing activities"


def test_legacy_symbols_outside_date_columns_are_attached_without_crossing_years():
    content = b'''<h2>Consolidated Statements of Cash Flows</h2>
    <p>Years ended December 31, in millions USD</p><table>
    <tr><td></td><td></td><td>2016</td><td></td><td></td><td>2015</td><td></td></tr>
    <tr><td>Purchase of equipment</td><td>($</td><td>12,000</td><td>)</td><td>$</td><td>1,000</td><td></td></tr>
    </table>'''
    filing = Filing(FILING.accession, "10-K", "2017-02-01", "2016-12-31", FILING.primary_document, FILING.source_url)
    values = {fact.end: fact.value for fact in parse_filing_html(content, filing)}
    assert values == {"2016-12-31": -12_000_000_000, "2015-12-31": 1_000_000_000}


def test_legacy_two_numbers_under_one_date_never_concatenated():
    rows = '<tr><td>Ambiguous row</td><td>1</td><td>2</td><td></td><td></td><td>3</td><td>4</td><td></td><td></td><td>5</td><td>6</td><td></td></tr>'
    assert parse_filing_html(legacy_table("Consolidated Statements of Income", rows), FILING) == []


def test_legacy_eps_uses_same_grouped_columns_without_dollar_scaling():
    rows = '<tr><td>Earnings per share:</td></tr>'
    rows += legacy_row("Basic", [3.25, 3.00, 2.5])
    rows += legacy_row("Diluted", [3.10, 2.90, 2.4])
    facts = parse_filing_html(legacy_table("Consolidated Statements of Income", rows), FILING)
    assert len(facts) == 6
    assert {fact.unit for fact in facts} == {"USD/shares"}
    assert {fact.section for fact in facts} == {"Earnings per share"}
    assert next(fact.value for fact in facts if fact.label == "Diluted" and fact.end == "2016-09-24") == 3.10


def test_share_count_heading_containing_earnings_per_share_does_not_become_eps():
    rows = '<tr><td>Earnings per share:</td></tr>' + legacy_row("Basic", [3.25, 3.00, 2.5])
    rows += '<tr><td>Shares used in computing earnings per share:</td></tr>' + legacy_row("Basic", [180, 175, 170])
    facts = parse_filing_html(legacy_table("Consolidated Statements of Income", rows), FILING)
    assert len(facts) == 3
    assert max(fact.value for fact in facts) == 3.25


def test_same_other_label_retains_distinct_cashflow_sections():
    rows = ""
    for section, amounts in [("Operating activities", [1, 2, 3]), ("Investing activities", [1, 2, 3]), ("Financing activities", [1, 2, 3])]:
        rows += f'<tr><td>{section}:</td></tr>' + legacy_row("Other", amounts)
    facts = parse_filing_html(legacy_table("Consolidated Statements of Cash Flows", rows), FILING)
    assert len(facts) == 9
    assert {fact.section for fact in facts} == {"Operating activities", "Investing activities", "Financing activities"}


def test_balance_marketables_retain_current_noncurrent_context():
    rows = '<tr><td>Current assets:</td></tr>'
    rows += legacy_row("Marketable securities", [20, 21, 22])
    rows += legacy_row("Total current assets", [100, 101, 102])
    rows += legacy_row("Marketable securities", [200, 201, 202])
    facts = parse_filing_html(legacy_table("Consolidated Balance Sheets", rows), FILING)
    assert {(fact.section, fact.value) for fact in facts if fact.label == "Marketable securities" and fact.end == "2016-09-24"} == {("Current assets", 20_000_000), ("Non-current assets", 200_000_000)}


def test_legacy_cp1252_and_utf8_punctuation_produce_readable_labels():
    for encoding in ("cp1252", "utf-8"):
        content = legacy_table("Consolidated Balance Sheets", legacy_row("Total shareholders’ equity", [100, 90, 80])).decode().encode(encoding)
        facts = parse_filing_html(content, FILING)
        assert len(facts) == 3
        assert {fact.label for fact in facts} == {"Total shareholders’ equity"}


def test_inline_descriptor_tags_stay_out_of_statement_numeric_rows():
    content = b'''<html><body><ix:header><ix:resources>
    <xbrli:context id="i"><xbrli:period><xbrli:instant>2016-09-24</xbrli:instant></xbrli:period></xbrli:context>
    <xbrli:unit id="usd"><xbrli:measure>iso4217:USD</xbrli:measure></xbrli:unit>
    </ix:resources></ix:header><h2>Consolidated Balance Sheets</h2><table>
    <tr><td>Shareholders' equity:</td></tr>
    <tr><td>Common stock, $<ix:nonFraction name="us-gaap:CommonStockParOrStatedValuePerShare" contextRef="i" unitRef="usd">0.01</ix:nonFraction> par value</td>
    <td><ix:nonFraction name="us-gaap:CommonStockValue" contextRef="i" unitRef="usd" scale="6">25</ix:nonFraction></td></tr>
    </table></body></html>'''
    facts = parse_filing_html(content, FILING)
    assert len(facts) == 1
    assert facts[0].tag == "us-gaap:CommonStockValue"
    assert facts[0].value == 25_000_000
    assert facts[0].section == "Equity"
    assert facts[0].label == "Common stock, $0.01 par value"


def test_legacy_note_with_matching_title_is_not_a_primary_statement():
    rows = legacy_row("Revenue", [100, 90, 80])
    content = b'<h2>Notes to Consolidated Financial Statements</h2>' + legacy_table("Consolidated Statements of Income", rows)
    assert parse_filing_html(content, FILING) == []
