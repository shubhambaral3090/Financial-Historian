def test_conflicting_html_eps_uses_consistent_standardized_fact_from_same_filing():
    # Legacy export assigned the EPS unit to a later basic share-count row.
    inputs = [
        fact("html:profitloss:basic", "Basic", 8.35, unit="USD/shares", extraction="html-table"),
        fact("html:profitloss:basic", "Basic", 5_470_820, unit="USD/shares", extraction="html-table"),
        fact("us-gaap:EarningsPerShareBasic", "Earnings Per Share, Basic", 8.35, unit="USD/shares"),
    ]
    bundle = assemble(inputs)
    selected = keyed_rows(bundle, P)["eps_basic"].values["2016-09-30"]
    assert selected.value == 8.35
    assert selected.tag == "us-gaap:EarningsPerShareBasic"
    assert "Conflicting HTML observations were excluded" in selected.selection_reason
    assert len(bundle.raw_facts) == 3


def test_defined_fallback_cashflow_payment_and_asset_change_signs_preserve_source():
    inputs = [
        fact("us-gaap:PaymentsToAcquireProductiveAssets", "Payments to acquire productive assets", 10, statement=C),
        fact("us-gaap:IncreaseDecreaseInAccountsReceivable", "Increase in accounts receivable", 20, statement=C),
        fact("us-gaap:IncreaseDecreaseInAccountsPayable", "Increase in accounts payable", 30, statement=C),
    ]
    bundle = assemble(inputs)
    displayed = {row.tag: next(iter(row.values.values())) for row in bundle.statements[C]}
    assert displayed[inputs[0].tag].presentation_value == -10
    assert displayed[inputs[1].tag].presentation_value == -20
    assert displayed[inputs[2].tag].presentation_value is None
    assert [entry.value for entry in bundle.raw_facts] == [10, 20, 30]


def test_partial_html_recovers_broader_productive_assets_without_merging_ppe():
    inputs = [
        fact("html:cashflow:cash_generated_by_operating_activities", "Cash generated by operating activities", 18_595_000_000, 2010, statement=C, extraction="html-table"),
        fact("us-gaap:PaymentsToAcquireProductiveAssets", "Payments to acquire productive assets", 2_005_000_000, 2010, statement=C),
        fact("us-gaap:PaymentsToAcquirePropertyPlantAndEquipment", "Purchases of property, plant and equipment", 1_800_000_000, 2010, statement=C),
    ]
    bundle = assemble(inputs)
    rows = keyed_rows(bundle, C)
    assert {"productive_assets", "capex"} <= rows.keys()
    picked = rows["productive_assets"].values["2010-09-30"]
    assert picked.value == 2_005_000_000
    assert picked.presentation_value == -2_005_000_000
    assert picked.accession == inputs[1].accession
    assert "filled from a standardized fact" in picked.selection_reason
    assert bundle.raw_facts[1].value == 2_005_000_000
    assert bundle.raw_facts[1].presentation_value is None


def test_other_noncash_source_income_sign_inverts_only_for_fallback():
    source = fact("us-gaap:OtherNoncashIncomeExpense", "Other noncash income / expense", 652_000_000, 2019, statement=C)
    fallback = next(iter(assemble([source]).statements[C][0].values.values()))
    assert fallback.value == 652_000_000
    assert fallback.presentation_value == -652_000_000
    native = replace(source, extraction="inline-xbrl", presentation_value=-652_000_000)
    selected = next(iter(assemble([native]).statements[C][0].values.values()))
    assert selected.value == 652_000_000
    assert selected.presentation_value == -652_000_000


