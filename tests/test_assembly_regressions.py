"""Output-level regressions exposed by the user's multi-year Apple workbook."""
from dataclasses import replace

from financial_historian.extract import assemble_bundle
from financial_historian.models import Company, Fact, Filing, STATEMENTS
from financial_historian.normalization import concept_key

COMPANY = Company("320193", "Example company", "EX")
P, B, C = STATEMENTS


def filing(year):
    return Filing(f"0000320193-{year % 100:02d}-000001", "10-K", f"{year}-11-01", f"{year}-09-30", "annual.htm", f"https://www.sec.gov/Archives/edgar/data/320193/{year}/annual.htm")


def fact(tag, label, value, year=2016, *, statement=P, unit="USD", source=None, extraction="companyfacts", section="", presentation=None):
    source = source or filing(year + 2)
    return Fact(tag, label, unit, value, None if statement == B else f"{year - 1}-10-01", f"{year}-09-30", source.accession, source.filed, source.form, source.source_url, statement, extraction, presentation_value=presentation, section=section)


def assemble(facts):
    return assemble_bundle(COMPANY, [filing(2018), filing(2019)], facts, [], [])


def keyed_rows(bundle, statement):
    return {concept_key(next(iter(row.values.values()))): row for row in bundle.statements[statement]}


def test_html_and_renamed_revenue_tags_form_one_continuous_source_preserving_row():
    inputs = [
        fact("us-gaap:SalesRevenueNet", "Revenue, Net (Deprecated)", 100, 2009),
        fact("html:profitloss:net_sales", "Net sales", 110, 2016, extraction="html-table"),
        fact("us-gaap:RevenueFromContractWithCustomerExcludingAssessedTax", "Total net sales", 120, 2019, extraction="inline-xbrl"),
    ]
    bundle = assemble(inputs)
    assert len(bundle.statements[P]) == 1
    row = bundle.statements[P][0]
    assert row.label == "Revenue"
    assert row.is_total
    assert set(row.values) == {"2009-09-30", "2016-09-30", "2019-09-30"}
    assert row.accepted_tags == {entry.tag for entry in inputs}
    assert row.values["2016-09-30"].tag == "html:profitloss:net_sales"
    assert row.values["2009-09-30"].source_url == inputs[0].source_url


def test_partial_html_does_not_hide_same_filing_eps_shares_or_cash_totals():
    inputs = [
        fact("html:profitloss:net_income", "Net income", 45_687_000_000, extraction="html-table"),
        fact("us-gaap:EarningsPerShareBasic", "Earnings Per Share, Basic", 8.35, unit="USD/shares"),
        fact("us-gaap:EarningsPerShareDiluted", "Earnings Per Share, Diluted", 8.31, unit="USD/shares"),
        fact("us-gaap:WeightedAverageNumberOfSharesOutstandingBasic", "Basic", 5_470_820_000, unit="shares"),
        fact("html:cashflow:cash_generated_by_operating_activities", "Cash generated by operating activities", 66_231_000_000, statement=C, extraction="html-table"),
        fact("us-gaap:NetCashProvidedByUsedInInvestingActivities", "Investing cash flow", -45_977_000_000, statement=C),
        fact("us-gaap:NetCashProvidedByUsedInFinancingActivities", "Financing cash flow", -20_890_000_000, statement=C),
        fact("us-gaap:PaymentsToAcquirePropertyPlantAndEquipment", "Equipment payments", 12_734_000_000, statement=C),
    ]
    bundle = assemble(inputs)
    income = keyed_rows(bundle, P)
    cash = keyed_rows(bundle, C)
    assert income["eps_basic"].values["2016-09-30"].value == 8.35
    assert income["shares_basic"].values["2016-09-30"].value == 5_470_820_000
    assert {"cfo", "cfi", "cff", "capex"} <= cash.keys()
    assert cash["cfi"].values["2016-09-30"].value == -45_977_000_000
    capex = cash["capex"].values["2016-09-30"]
    assert capex.value == 12_734_000_000
    assert capex.presentation_value == -12_734_000_000
    assert "filled from a standardized fact" in capex.selection_reason
    assert all(entry.presentation_value is None for entry in bundle.raw_facts if entry.extraction == "companyfacts")


def test_newer_sparse_companyfacts_updates_known_row_without_destroying_old_balance_sheet():
    old, newer = filing(2008), filing(2010)
    inputs = [
        fact("html:balancesheet:total_assets", "Total assets", 25_347, 2007, statement=B, source=old, extraction="html-table"),
        fact("html:balancesheet:total_liabilities", "Total liabilities", 10_815, 2007, statement=B, source=old, extraction="html-table"),
        fact("html:balancesheet:total_shareholders_equity", "Total shareholders\x92 equity", 14_532, 2007, statement=B, source=old, extraction="html-table"),
        fact("us-gaap:StockholdersEquity", "Stockholders equity", 14_531, 2007, statement=B, source=newer),
    ]
    bundle = assemble(inputs)
    rows = keyed_rows(bundle, B)
    assert set(rows) == {"assets", "liabilities", "equity"}
    assert rows["assets"].values["2007-09-30"].value == 25_347
    assert rows["equity"].values["2007-09-30"].value == 14_531
    assert rows["equity"].values["2007-09-30"].filed == newer.filed
    assert any("multiple filings" in warning for warning in bundle.warnings)


